#!/usr/bin/env python3
"""fbw_tracking.py - does the fly-by-wire cost tracking? (FLY_BY_WIRE_2.md section 1; existing runs only, no simulation)

Pairs every test motion run by the pilot ALONE and by the same pilot WITH FBW (same motion, noise, seed), and splits them into
  S  pass / pass   cost of the shield where it was not needed      R  fail / pass   rescued
  F  fail / fail   blind spot (what did the shield see?)           X  pass / fail   regression
Per motion, from the per-step observation each run logged (--uq-out npz): joint tracking error = mean over steps and joints of
|joint angle - reference joint angle one step ahead| (rad; obs 0:29 vs 99:128), its 95th percentile over steps, and steps survived.
The evaluator's own errors are means per library run, not per motion, so they cannot be paired; this per-step measure can.
For F, from <tag>_fbw.npz: did the shield predict a fall (pfall > 0) in the 25 steps before the failure, and did it intervene.

    python3 fbw_tracking.py --alone <student-alone runs> --alone_arm r7c_mwv3ctl-s100 --fbw results_runs --fbw_arm fbwD_<tag> \
        --out results/retry/SUMMARY_fbw_tracking.md
"""
import os, glob, argparse
import numpy as np

Q, REF = slice(0, 29), slice(99, 128)
PRE = 25


def units(evdir, arm):
    """{(motion, noise, seed, episode): dict} for every test motion of this arm."""
    out = {}
    for npz in sorted(glob.glob(os.path.join(evdir, f"{arm}__*.npz"))):
        if npz.endswith("_fbw.npz"):
            continue
        tag = os.path.basename(npz)[:-4]; _, motion, nz, sd = tag.split("__")[:4]
        d = np.load(npz, allow_pickle=True)
        obs = d["obs"]; n = len(obs)
        if n == 0:
            continue
        ep = d["episode"] if "episode" in d.files and len(d["episode"]) == n else np.zeros(n, int)
        fails = {int(e): int(s) for e, s in d["ep_fail"].reshape(-1, 2)} if d["ep_fail"].size else {}
        if not fails and int(d["fail_step"]) >= 0 and len(np.unique(ep)) == 1:
            fails = {int(ep[0]): int(d["fail_step"])}
        fz = npz[:-4] + "_fbw.npz"; f = np.load(fz) if os.path.exists(fz) else None
        err = np.abs(obs[:, Q] - obs[:, REF]).mean(1)
        base = int(np.unique(ep).min())
        for e in np.unique(ep):
            idx = np.nonzero(ep == e)[0]
            r = dict(ok=int(e) not in fails, steps=len(idx), err=float(err[idx].mean()), err95=float(np.quantile(err[idx], 0.95)))
            if f is not None and len(f["inter"]) == n:
                r["inter"] = float(f["inter"][idx].mean())
                if int(e) in fails:
                    t = fails[int(e)]; w = idx[(idx >= t - PRE) & (idx <= t)]
                    r["pfall_pre"] = float(f["pfall"][w].max()) if len(w) else np.nan
                    r["inter_pre"] = float(f["inter"][w].mean()) if len(w) else np.nan
                    r["first_warn"] = int(t - idx[f["pfall"][idx] > 0][0]) if (f["pfall"][idx] > 0).any() else -1
            out[(motion, nz, sd, int(e) - base)] = r
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--alone", required=True); ap.add_argument("--alone_arm", required=True)
    ap.add_argument("--fbw", required=True); ap.add_argument("--fbw_arm", required=True); ap.add_argument("--out", required=True)
    a = ap.parse_args()
    A, F = units(a.alone, a.alone_arm), units(a.fbw, a.fbw_arm)
    keys = sorted(set(A) & set(F))
    G = {"S": [], "R": [], "F": [], "X": []}
    for k in keys:
        G[{(1, 1): "S", (0, 1): "R", (0, 0): "F", (1, 0): "X"}[(int(A[k]["ok"]), int(F[k]["ok"]))]].append(k)
    L = [f"# FBW tracking cost: `{a.fbw_arm}` vs `{a.alone_arm}` alone", "",
         "Generated by `step1_extraction/flight_computer/fbw_tracking.py` from existing runs. Unit = one test motion (library episode or one dance-clip run).",
         "Tracking error = mean |joint angle - reference joint angle (+1 step)| in rad, from the logged observations.", "",
         f"Paired units: {len(keys)} (alone only: {len(set(A) - set(F))}, FBW only: {len(set(F) - set(A))}).", "",
         "| group | meaning | n |", "|---|---|---|"]
    for g, txt in (("S", "pass alone, pass with FBW"), ("R", "fail alone, pass with FBW (rescued)"),
                   ("F", "fail both"), ("X", "pass alone, fail with FBW (regression)")):
        L.append(f"| {g} | {txt} | {len(G[g])} |")
    # S: paired cost
    if G["S"]:
        ea = np.array([A[k]["err"] for k in G["S"]]); ef = np.array([F[k]["err"] for k in G["S"]])
        e95a = np.array([A[k]["err95"] for k in G["S"]]); e95f = np.array([F[k]["err95"] for k in G["S"]])
        rel = (ef - ea) / ea; rel95 = (e95f - e95a) / e95a
        inter = np.array([F[k].get("inter", np.nan) for k in G["S"]])
        L += ["", "## S - cost of the shield where it was not needed (paired)", "",
              "| metric | alone (mean) | FBW (mean) | paired delta: median | mean | worst | units > +10 % |", "|---|---|---|---|---|---|---|",
              f"| joint tracking err (rad) | {ea.mean():.4f} | {ef.mean():.4f} | {100 * np.median(rel):+.1f} % | {100 * rel.mean():+.1f} % | "
              f"{100 * rel.max():+.1f} % | {(rel > 0.10).sum()} / {len(rel)} |",
              f"| p95 over steps | {e95a.mean():.4f} | {e95f.mean():.4f} | {100 * np.median(rel95):+.1f} % | {100 * rel95.mean():+.1f} % | "
              f"{100 * rel95.max():+.1f} % | {(rel95 > 0.10).sum()} / {len(rel95)} |",
              "", f"FBW interventions on S units: median {100 * np.nanmedian(inter):.1f} % of steps, max {100 * np.nanmax(inter):.1f} %.",
              f"Units with 0 interventions: {(inter == 0).sum()} / {len(inter)} (their delta should be exactly 0: "
              f"max |delta| there = {np.abs(rel[inter == 0]).max() * 100 if (inter == 0).any() else float('nan'):.2f} %).",
              "", "Worst five S units:", "", "| unit (motion, noise, seed, episode) | alone err | FBW err | delta | FBW interventions |", "|---|---|---|---|---|"]
        for i in np.argsort(-rel)[:5]:
            k = G["S"][i]; L.append(f"| {k} | {ea[i]:.4f} | {ef[i]:.4f} | {100 * rel[i]:+.1f} % | {100 * inter[i]:.1f} % |")
        sdist = ef
    if G["R"]:
        L += ["", "## R - rescued (FBW tracking vs the S distribution)", "",
              "| unit | steps alone (fell) | FBW err | percentile among S (FBW) | FBW interventions |", "|---|---|---|---|---|"]
        for k in G["R"]:
            p = 100 * (sdist < F[k]["err"]).mean() if G["S"] else np.nan
            L.append(f"| {k} | {A[k]['steps']} | {F[k]['err']:.4f} | {p:.0f} | {100 * F[k].get('inter', np.nan):.1f} % |")
    if G["F"]:
        L += ["", f"## F - fail both: what did the shield see in the last {PRE} steps?", "",
              "| unit | steps alone | steps FBW | FBW predicted a fall (max pfall) | first warning, steps before failure | interventions in window |",
              "|---|---|---|---|---|---|"]
        for k in G["F"]:
            f = F[k]
            L.append(f"| {k} | {A[k]['steps']} | {f['steps']} | {f.get('pfall_pre', np.nan):.2f} | {f.get('first_warn', -1)} | "
                     f"{100 * f.get('inter_pre', np.nan):.0f} % |")
        L += ["", "Reading: max pfall 0 = the shield never saw the fall coming in its look-ahead (horizon / model blind spot); "
              "pfall > 0 with interventions = it saw it and its corrections were not enough (authority / search)."]
    L += ["", "## X - regressions", "", f"{len(G['X'])} units." + ("" if not G["X"] else " " + ", ".join(map(str, G["X"])))]
    os.makedirs(os.path.dirname(os.path.abspath(a.out)), exist_ok=True)
    open(a.out, "w").write("\n".join(L) + "\n"); print("\n".join(L))


if __name__ == "__main__":
    main()
